const DOTA_EMOTICON_SET = new Set(DOTA_EMOTICONS);
export const isDotaEmoticon = (name) => DOTA_EMOTICON_SET.has(name);
export const dotaEmoticonSrc = (name) => `img/emoticons/${name}.gif`;
export const dotaEmoticonLabel = (name) => name
  .replace(/^(bc_|dac15_|charm_)/, '')
  .replace(/_ti6_charm$/, '')
  .replaceAll('_', ' ')
  .replace(/\b\w/g, (c) => c.toUpperCase());

// Split comment text into safe-to-escape strings and known emoticon tokens. Unknown codes stay text.
export function emoticonParts(text) {
  const parts = [], pattern = /:([a-z0-9_]+):/gi;
  let from = 0, match;
  while ((match = pattern.exec(String(text ?? '')))) {
    const name = match[1].toLowerCase();
    if (!DOTA_EMOTICON_SET.has(name)) continue;
    if (match.index > from) parts.push(String(text).slice(from, match.index));
    parts.push({ name });
    from = pattern.lastIndex;
  }
  if (from < String(text ?? '').length) parts.push(String(text).slice(from));
  return parts.length ? parts : [String(text ?? '')];
}

// The active :prefix immediately before the caret, plus its best catalog matches.
export function emoticonCompletion(value, caret = String(value ?? '').length, limit = 10) {
  const before = String(value ?? '').slice(0, caret);
  const match = before.match(/(^|[\s(]):([a-z0-9_]*)$/i);
  if (!match) return null;
  const query = match[2].toLowerCase();
  const matches = DOTA_EMOTICONS.filter((name) => name.startsWith(query)).slice(0, limit);
  if (!matches.length) return null;
  return { start: caret - query.length - 1, end: caret, query, matches };
}

export function insertEmoticon(value, completion, name) {
  const text = String(value ?? '');
  const inserted = `:${name}: `;
  return {
    value: text.slice(0, completion.start) + inserted + text.slice(completion.end),
    caret: completion.start + inserted.length,
  };
}

