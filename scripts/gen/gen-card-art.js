// Package the art choices from the dev picker for the compact player card editor.
// Source mapping is committed; wiki originals are copied from _dev to avoid blocked hotlinks.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
const root = new URL("../../", import.meta.url);
const sources = JSON.parse(await readFile(new URL("card-art-sources.json", import.meta.url)));
await mkdir(new URL("public/img/card-art/", root), { recursive: true });
const copied = new Set(), catalog = {};
for (const [name, rows] of Object.entries(sources)) {
  catalog[name] = [];
  for (const row of rows) {
    if (/mini[\s_-]*heroes/i.test(row.label)) continue;
    if (row.local && !copied.has(row.src)) {
      let image;
      try { image = await readFile(new URL(`public/${row.local}`, root)); }
      catch {
        // Already packaged assets let this generator run on an ordinary checkout.
        try { image = await readFile(new URL(`public/${row.src}`, root)); }
        catch { const r = await fetch(row.original); if (!r.ok) throw new Error(`Art: HTTP ${r.status}`); image = Buffer.from(await r.arrayBuffer()); }
      }
      await sharp(image).resize({ width: 560, withoutEnlargement: true }).webp({ quality: 76 }).toFile(fileURLToPath(new URL(`public/${row.src}`, root)));
      copied.add(row.src);
    }
    catalog[name].push({ id: row.id, label: row.label, src: row.src, cls: row.cls });
  }
}
await writeFile(new URL("public/lib/card-art-data.js", root), `// Generated by scripts/gen/gen-card-art.js from the original art picker.
export const CARD_ART = ${JSON.stringify(catalog)};
`);
console.log(`${Object.keys(catalog).length} hero galleries, ${copied.size} local art files.`);
