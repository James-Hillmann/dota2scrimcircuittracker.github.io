// Refresh local team logos from the verified Dotabuff directory mapping.
// The PlayOn -> Dota IDs were matched using radiant_team_id/dire_team_id in S48 replays.
// Usage: node scripts/gen/team-logos.js (downloads only missing originals); add --refresh to refetch.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
const sources = JSON.parse(await readFile(new URL("./team-logo-sources.json", import.meta.url)));
const root = new URL("../../", import.meta.url);
await mkdir(new URL("public/img/teams/", root), { recursive: true });
await mkdir(new URL(".cache/team-logos/", root), { recursive: true });
const logos = {};
for (const [id, source] of Object.entries(sources)) {
  const cached = new URL(`.cache/team-logos/${id}.png`, root);
  let bytes;
  try { if (process.argv.includes("--refresh")) throw new Error(); bytes = await readFile(cached); }
  catch {
    const response = await fetch(source.source);
    if (!response.ok) throw new Error(`Logo ${id}: HTTP ${response.status}`);
    bytes = Buffer.from(await response.arrayBuffer());
    await writeFile(cached, bytes);
  }
  await sharp(bytes).resize(128, 128, { fit: "inside", withoutEnlargement: true }).webp({ quality: 88 }).toFile(fileURLToPath(new URL(`public/${source.file}`, root)));
  logos[id] = { name: source.name, file: source.file };
}
await writeFile(new URL("public/lib/team-logo-data.js", root), `// Generated by scripts/gen/team-logos.js. Source URLs and verified Dota IDs are in its sources file.
export const TEAM_LOGOS = ${JSON.stringify(logos, null, 2)};
`);
console.log(`Saved ${Object.keys(logos).length} team logos (128px maximum).`);
