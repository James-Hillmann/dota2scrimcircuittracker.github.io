// Writes the Fantasy cards' hero art: public/img/hero-art/<slug>.webp (one image per hero, max
// 560px wide) and public/lib/hero-art.js (each hero's card style and crop class).
// The picks are Fav's, in scripts/gen/hero-art-picks.json: slug -> { hero, style, cls, label, src }.
// src is the original image (Dota 2 wiki, Valve's CDN or the Steam market); the wiki blocks
// hotlinking, so the site serves its own copies.
// Run: node scripts/gen/gen-hero-art.js
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import sharp from "sharp";

const root = new URL("../../", import.meta.url);
const picks = JSON.parse(readFileSync(new URL("scripts/gen/hero-art-picks.json", root), "utf8"));
const dir = new URL("public/img/hero-art/", root);
mkdirSync(dir, { recursive: true });

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function get(url) {
  for (let t = 0; t < 4; t++) {
    try { const r = await fetch(url, { headers: { "user-agent": "Mozilla/5.0" } }); if (r.ok) return Buffer.from(await r.arrayBuffer()); } catch {}
    await sleep(2000);
  }
  throw new Error(`download failed: ${url}`);
}

let bytes = 0;
for (const [slug, p] of Object.entries(picks)) {
  const out = await sharp(await get(p.src)).resize({ width: 560, withoutEnlargement: true }).webp({ quality: 78 }).toBuffer();
  writeFileSync(new URL(`${slug}.webp`, dir), out);
  bytes += out.length;
}

const map = Object.fromEntries(Object.entries(picks).map(([slug, p]) => [slug, [p.style, p.cls]]));
writeFileSync(new URL("public/lib/hero-art.js", root), `// Generated by scripts/gen/gen-hero-art.js from scripts/gen/hero-art-picks.json: hero image slug ->
// [card style, art crop class]. Styles are in style.css (.ft-card[data-style]); images in img/hero-art/.
import { HERO_META } from "./hero-meta.js";

export const HERO_ART = ${JSON.stringify(map)};

const slugOf = new Map(HERO_META.map(([, n, s]) => [n.toLowerCase(), s]));
// A hero's Fantasy card art: { src, style, cls }, or null for a hero with no pick yet (a new hero).
export function heroArt(name) {
  const slug = slugOf.get(String(name ?? "").toLowerCase()), a = slug && HERO_ART[slug];
  return a ? { src: \`img/hero-art/\${slug}.webp\`, style: a[0], cls: a[1] } : null;
}
`);
console.log(`${Object.keys(picks).length} heroes, ${(bytes / 1048576).toFixed(1)} MB in public/img/hero-art/`);
